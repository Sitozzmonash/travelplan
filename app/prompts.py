INTENT_PARSE_PROMPT = """请把用户的自然语言旅行需求解析成结构化 JSON。

只输出一个 JSON 对象，不要输出解释、不要用 markdown 代码块包裹。

字段说明（缺失就给 null，不要猜、不要填默认值）：
- origin_city: 出发城市（字符串或 null）
- destination_city: 目的地城市（字符串或 null）
- start_date: 出发日期，格式 YYYY-MM-DD（字符串或 null）
- end_date: 返回/结束日期，格式 YYYY-MM-DD（字符串或 null）
- days: 行程天数（整数或 null）。用户说"三天两晚"时，days=3
- travelers: 出行人数（整数或 null）
- budget: 总预算（数字，人民币元；或 null）。用户说"人均 3000"时请换算成总预算并保持人数一致
- pace: 节奏，只能是 "relaxed" | "normal" | "packed" 之一，或 null
- preferences: 偏好关键词数组（如 ["美食", "博物馆", "亲子", "不爬山"]），没有就给空数组 []
- avoid: 明确不想去的类型数组，没有就给 []
- transport_preference: 交通偏好，如 "高铁" | "飞机" | "自驾"，或 null
- hotel_level: 住宿档次要求（如 "经济型" | "四星" | "民宿"），或 null
- raw_text: 原样保留用户原始输入

容错要求（很重要）：
- 用户没说日期、没说人数、没说预算时，对应字段必须是 null，不要瞎填一个看起来合理的值。
- 日期如果只给了"国庆""下个月第一个周末"这种模糊说法，解析不了就填 null，并在 raw_text 里保留原文。
- 数字可能是中文（"两个人""三千块"），请正常换算成整数。
- 遇到你没把握的字段，宁可 null，也不要编。"""


